"""EXP26 — Paired bootstrap of the near-line gap (random-direction rate minus observed rate), same addresses.

Per address: d_i = p_random_dir_i - wrong_i (p_random_dir = share of 200 random directions landing in another tract).
Address bootstrap (5,000 reps) and county-cluster bootstrap (clusters = county of the Census-returned geocode).
Writes results/v2_paired_gap/summary.txt and paper/paired_gap.tex (LaTeX macros used by main.tex).

    python experiments/exp26_paired_gap.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
import numpy as np
import pandas as pd

from src import config as C
from src.report import Report

RES = C.out_dir(C.RESULTS, "v2_paired_gap")
rep = Report("EXP26 paired bootstrap of the observed vs random-direction gap (near-line)", RES)


def as_bool(s):
    return s.astype(str).str.lower().isin(["true", "1", "1.0"])


nyc = pd.read_csv(f"{C.RAW}/nyc/nyc_direction_counterfactual.csv")
nyc["source"] = np.where(nyc["sample"] == "PLUTO", "NYC, PLUTO", "NYC, Address Points")
ut = pd.read_csv(f"{C.RAW}/utah/utah_points.csv")
ut = ut[~ut["PtLocation"].fillna("").str.contains("Geocod", case=False)].copy(); ut["source"] = "Utah"
na = pd.read_csv(f"{C.RAW}/nad/national_points.csv"); na["source"] = "National"
A = pd.concat([d[["source", "uid", "stratum", "wrong", "p_random_dir"]] for d in (nyc, ut, na)], ignore_index=True)
A = A[A["stratum"].astype(str).str.startswith("near")].copy()
A["wrong"] = as_bool(A["wrong"]).astype(float)
cg = []
for src, path in [("NYC, PLUTO", f"{C.RAW}/nyc/census_geocoded.csv"), ("NYC, Address Points", f"{C.RAW}/nyc/census_geocoded_ap.csv"),
                  ("Utah", f"{C.RAW}/utah/census_geocoded.csv"), ("National", f"{C.RAW}/nad/census_geocoded.csv")]:
    d = pd.read_csv(path, dtype=str); d["source"] = src
    d["uid"] = pd.to_numeric(d["uid"], errors="coerce"); d = d.dropna(subset=["uid"]); d["uid"] = d["uid"].astype(int)
    d["fips"] = d["st"].fillna("").str.zfill(2) + d["co"].fillna("").str.zfill(3)
    cg.append(d[d["match"] == "Match"][["source", "uid", "fips"]])
A = A.merge(pd.concat(cg), on=["source", "uid"], how="left")
A["d"] = A["p_random_dir"] - A["wrong"]
n = len(A); gap = 100 * A["d"].mean()
rng = np.random.default_rng(26)
dv = A["d"].to_numpy()
ab = np.array([dv[rng.integers(0, n, n)].mean() for _ in range(5000)]) * 100
cl = A["fips"].fillna("NA").to_numpy(); cs = np.unique(cl); idx = {c: np.where(cl == c)[0] for c in cs}
cb = []
for _ in range(5000):
    pick = rng.choice(cs, len(cs))
    ii = np.concatenate([idx[c] for c in pick]); cb.append(100 * dv[ii].mean())
cb = np.array(cb)
lo_a, hi_a = np.percentile(ab, [2.5, 97.5]); lo_c, hi_c = np.percentile(cb, [2.5, 97.5])
rep.say(f"[G1] near-line n={n}, observed {100*A['wrong'].mean():.3f}%, random-direction {100*A['p_random_dir'].mean():.3f}%, "
        f"gap {gap:.2f} points")
rep.say(f"[G2] paired address bootstrap 95% CI [{lo_a:.2f}, {hi_a:.2f}]; county-cluster bootstrap ({len(cs)} counties) [{lo_c:.2f}, {hi_c:.2f}]")
open(os.path.join(os.path.dirname(__file__), "..", "paper", "paired_gap.tex"), "w").write(
    f"% generated by experiments/exp26_paired_gap.py\n\\newcommand{{\\gapval}}{{{gap:.1f}}}\n"
    f"\\newcommand{{\\gapaddr}}{{{lo_a:.1f}--{hi_a:.1f}}}\n\\newcommand{{\\gapcounty}}{{{lo_c:.1f}--{hi_c:.1f}}}\n"
    f"\\newcommand{{\\gapncounty}}{{{len(cs)}}}\n")
rep.save()
