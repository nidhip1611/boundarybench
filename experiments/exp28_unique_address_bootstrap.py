"""EXP28 — Unique-address bootstrap of the near-line paired gap (reviewer request). Same data as EXP26; the
resampling unit is the matched output address, so the 8 near-line addresses that occur twice (EXP27) are one cluster.
Writes results/v2_unique_boot/summary.txt and paper/unique_boot.tex (macro \\gapuniq used by main.tex).

    python experiments/exp28_unique_address_bootstrap.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
import numpy as np
import pandas as pd

from src import config as C
from src.report import Report

RES = C.out_dir(C.RESULTS, "v2_unique_boot")
rep = Report("EXP28 unique-address bootstrap of the observed vs random-direction gap (near-line)", RES)


def as_bool(s):
    return s.astype(str).str.lower().isin(["true", "1", "1.0"])


nyc = pd.read_csv(f"{C.RAW}/nyc/nyc_direction_counterfactual.csv")
nyc["source"] = np.where(nyc["sample"] == "PLUTO", "NYC, PLUTO", "NYC, Address Points")
ut = pd.read_csv(f"{C.RAW}/utah/utah_points.csv")
ut = ut[~ut["PtLocation"].fillna("").str.contains("Geocod", case=False)].copy(); ut["source"] = "Utah"
na = pd.read_csv(f"{C.RAW}/nad/national_points.csv"); na["source"] = "National"
A = pd.concat([d[["source", "uid", "stratum", "wrong", "p_random_dir"]] for d in (nyc, ut, na)], ignore_index=True)
A = A[A["stratum"].astype(str).str.startswith("near")].copy()
A["wrong"] = as_bool(A["wrong"]).astype(float)
cg = []
for src, path in [("NYC, PLUTO", f"{C.RAW}/nyc/census_geocoded.csv"), ("NYC, Address Points", f"{C.RAW}/nyc/census_geocoded_ap.csv"),
                  ("Utah", f"{C.RAW}/utah/census_geocoded.csv"), ("National", f"{C.RAW}/nad/census_geocoded.csv")]:
    d = pd.read_csv(path, dtype=str); d["source"] = src
    d["uid"] = pd.to_numeric(d["uid"], errors="coerce"); d = d.dropna(subset=["uid"]); d["uid"] = d["uid"].astype(int)
    d["key"] = d["out_address"].fillna("").str.upper().str.strip()
    cg.append(d[d["match"] == "Match"][["source", "uid", "key"]])
A = A.merge(pd.concat(cg), on=["source", "uid"], how="left")
A["key"] = A["key"].fillna("") 
A.loc[A["key"] == "", "key"] = "row" + A.index.astype(str)
A["d"] = A["p_random_dir"] - A["wrong"]
n = len(A); gap = 100 * A["d"].mean()
dv = A["d"].to_numpy(); kv = A["key"].to_numpy(); ks = np.unique(kv)
idx = {k: np.where(kv == k)[0] for k in ks}
rng = np.random.default_rng(28)
ub = []
for _ in range(5000):
    pick = rng.choice(ks, len(ks))
    ii = np.concatenate([idx[k] for k in pick]); ub.append(100 * dv[ii].mean())
lo, hi = np.percentile(ub, [2.5, 97.5])
rep.say(f"[U1] near-line rows {n}, unique matched addresses {len(ks)}, repeated addresses {int(sum(len(v) > 1 for v in idx.values()))}")
rep.say(f"[U2] gap {gap:.2f} points; unique-address bootstrap 95% CI [{lo:.2f}, {hi:.2f}] (5,000 reps)")
open(os.path.join(os.path.dirname(__file__), "..", "paper", "unique_boot.tex"), "w").write(
    f"% generated by experiments/exp28_unique_address_bootstrap.py\n\\newcommand{{\\gapuniq}}{{{lo:.1f}--{hi:.1f}}}\n")
rep.save()
